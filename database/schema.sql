create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  school text not null unique,
  conference text,
  classification text,
  is_power boolean default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  cfbd_game_id bigint unique,
  season integer not null,
  week integer not null,
  model_week integer,
  season_type text not null default 'regular',
  home_team text not null,
  away_team text not null,
  home_points integer,
  away_points integer,
  start_date timestamptz,
  neutral_site boolean default false,
  completed boolean default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.team_game_stats (
  id bigint generated by default as identity primary key,
  game_id bigint references public.games(id) on delete cascade,
  cfbd_game_id bigint,
  season integer not null,
  week integer not null,
  model_week integer,
  season_type text not null default 'regular',
  team text not null,
  opponent text not null,
  is_home boolean,
  ppa_off numeric,
  ppa_def numeric,
  success_off numeric,
  success_def numeric,
  pts_per_drive_off numeric,
  pts_per_drive_def numeric,
  rush_ppa_off numeric,
  rush_ppa_def numeric,
  pass_ppa_off numeric,
  pass_ppa_def numeric,
  rush_rate_off numeric,
  pass_rate_off numeric,
  raw jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (season, week, team, opponent)
);

create table if not exists public.roster_players (
  id bigint generated by default as identity primary key,
  season integer not null,
  team text not null,
  player_name text not null,
  position text,
  rating numeric,
  class_year text,
  source text default 'on3',
  raw jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (season, team, player_name, position)
);

create table if not exists public.on3_roster_sources (
  id bigint generated by default as identity primary key,
  season integer not null,
  team text not null,
  url text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (season, team)
);

create table if not exists public.coach_configs (
  id bigint generated by default as identity primary key,
  team text not null unique,
  coach_name text,
  tier text not null default 'Average' check (tier in ('Elite', 'Good', 'Average', 'Concerning', 'Unknown')),
  hire_year integer,
  off_tendency integer not null default 3 check (off_tendency between 1 and 5),
  def_tendency integer not null default 3 check (def_tendency between 1 and 5),
  offense_rating integer not null default 5 check (offense_rating between 1 and 10),
  defense_rating integer not null default 5 check (defense_rating between 1 and 10),
  development_rating text not null default 'Average' check (development_rating in ('Elite', 'Good', 'Average', 'Poor', 'Terrible')),
  preseason_override numeric,
  notes text,
  source text not null default 'manual',
  updated_at timestamptz not null default now()
);

create table if not exists public.model_configs (
  id bigint generated by default as identity primary key,
  name text not null unique,
  pass_weight numeric not null default 0.30,
  rush_weight numeric not null default 0.20,
  overall_weight numeric not null default 0.25,
  composite_weight numeric not null default 0.25,
  points_per_rating numeric not null default 1.4,
  home_field numeric not null default 2.5,
  margin_shrink numeric not null default 0.75,
  max_margin numeric not null default 24.5,
  coach_offense_boost numeric not null default 0.6,
  coach_defense_boost numeric not null default 0.6,
  coach_development_boost numeric not null default 1.0,
  rating_recency_weight numeric not null default 2.5,
  rating_talent_weight numeric not null default 0.4,
  rating_historical_position_weight numeric not null default 0.3,
  rating_preseason_position_weight numeric not null default 0.7,
  rating_talent_ramp_weeks numeric not null default 8,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

