grant usage, select on all sequences in schema public to service_role;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'teams',
    'games',
    'team_game_stats',
    'roster_players',
    'on3_roster_sources',
    'coach_configs',
    'model_configs',
    'ratings',
    'predictions',
    'backtest_games',
    'backtest_summary',
    'weight_optimizer',
    'model_buckets',
    'job_runs'
  ]
  loop
    execute format('drop policy if exists "public read %s" on public.%I', table_name, table_name);
    execute format('create policy "public read %s" on public.%I for select using (true)', table_name, table_name);
  end loop;
end $$;
